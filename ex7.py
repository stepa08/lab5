# запрашиваем у пользователя размеры фигур
n = int(input("Введите высоту: "))
m = int(input("Введите ширину: "))

print("\nПрямоугольник")
# выводим высоту фигуры
for i in range(n):
    # создаем строку из m звезд
    print("*" * m)

print("\nТреугольник")
# выводим высоту фигуры
for i in range(1, n + 1):
    # печатем все большее количество звезд
    print(i * "*")

print("\nЁлочка")
# выводим высоту фигуры
for i in range(1, n + 1):
    # сначала печатаем пробелы для выравнивания, потом выводим звезды
    print(' ' * (n - i) + '*' * (2*i - 1))

print("\nРомб")
# верхняя полловина ромба
for i in range(1, n + 1):
    # сначала печатаем пробелы для выравнивания (уменьшаются с каждой строкой), потом выводим звезды (увеличиваются с каждой строкой)
    print(' ' * (n - i) + '*' * (2*i - 1))
# нижняя половина ромба
for i in range(n - 1, 0, -1):
    # сначала печатаем пробелы для выравнивания (увеличиваются с каждой строкой), потом выводим звезды (уменьшаются с каждой строкой)
    print(' ' * (n - i) + '*' * (2*i - 1))