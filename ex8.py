try:
    # запрашиваем у пользователя целое число и сразу преобразуем в int
    number = int(input("Введите число: "))

    # в переменной храним сумму делителей числа
    sumDel = 0
    # перебираем все делители от 1 до number - 1
    for i in range(1, number):
        if number % i == 0:
            # считаем сумму делителей
            sumDel += i

    if sumDel == number:
        print(f"число {number} - совершенное")
    else:
        print(f"число {number} - не совершенное")

except ValueError:
    # обрабатываем ситуацию кога пользователь ввел не целое число или вообще не число
    print("Ошибка: нужно ввести целое число")