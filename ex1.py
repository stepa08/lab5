import math

# выводим шапку таблицы
# {value:>8} выравнивает текст по правому краю в поле шириной 8 символов
# {value:>10} выравниает текст по правому краю в поле шириной 10 символов
print(f"{'x':>8} {'sin(x)':>10}")
print("-" * 20)

for i in range(11):
    x = i * math.pi / 10
    # вычисляем значение sin в точке x
    y = math.sin(x)
    # выводим значения с округлением до 4 знаков после запятой
    print(f"{x:8.4f} {y:10.4f}")